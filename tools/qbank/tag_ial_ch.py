def tag(text, topics):
    lo = min(topics)
    hits = [k for k, rx in RX.items() if (int(k.split(".")[0]) in topics or (k in CARRY and int(k.split(".")[0]) < lo))
            and rx.search(text)]
    strong = [k for k in hits if k not in WEAK]
    keep = strong if strong else hits
    key = lambda k: tuple(int(x) for x in k.split("."))
    return sorted(set(keep), key=key)[:6]


def main():
    ext_dir, out = sys.argv[1], sys.argv[2]
    draft = {}
    for f in sorted(glob.glob(f"{ext_dir}/ext-*.json")):
        for paper, r in sorted(json.load(open(f)).items()):
            pid = paper[:-4]
            topics = UNIT_TOPICS[pid[:5]]
            for q in r["questions"]:
                key = f"{pid}-q{q['q']}"
                if q.get("parts"):
                    stem = q.get("stem_text", "")
                    tags = {}
                    for p in q["parts"]:
                        t = p["text"]
                        i = t.find(f"({p['label']})")
                        t = t[i:] if i >= 0 else t        # leftover options of the part before
                        tags[p["label"]] = tag(stem + " " + t, topics) or tag(q["text"], topics)[:3]
                    draft[key] = tags
                else:
                    draft[key] = tag(q["text"], topics)
    json.dump(draft, open(out, "w"), indent=0)


if __name__ == "__main__":
    main()
